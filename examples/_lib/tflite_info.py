"""Inspect a .tflite file for microcontroller deployment (used by several examples).

usage: python -I tflite_info.py info F.tflite [F2.tflite ...]   I/O types, size, gzip size, ops, arena estimate
       python -I tflite_info.py json F.tflite                   the same as JSON (one object)
       python -I tflite_info.py weights F.tflite                per weight tensor: zero fraction, unique values
       python -I tflite_info.py carray F.tflite NAME OUTDIR      NAME_model_data.{h,c} + NAME_op_resolver.h (TFLM)

The arena estimate is the sum of all non-constant tensors (an upper bound; TFLM's planner reuses memory,
so the real arena is smaller). Exit 1 on a file that is not a TFLite flatbuffer.
"""
import gzip
import json
import sys
from pathlib import Path

import numpy as np
import tflite  # flatbuffer schema bindings (installed with Kenning's tflite extra)

DTYPE_SIZE = {0: 4, 1: 2, 2: 4, 3: 1, 4: 8, 6: 1, 7: 2, 9: 1, 10: 8, 16: 4}   # tflite.TensorType -> bytes
DTYPE_NAME = {v: k for k, v in vars(tflite.TensorType).items() if not k.startswith("_")}
DTYPE_NP = {0: np.float32, 1: np.float16, 2: np.int32, 3: np.uint8, 4: np.int64, 7: np.int16, 9: np.int8}
OP_NAME = {v: k for k, v in vars(tflite.BuiltinOperator).items() if not k.startswith("_")}


def load(path: Path) -> tflite.Model:
    buf = path.read_bytes()
    if buf[4:8] != b"TFL3":
        raise SystemExit(f"{path}: not a TFLite flatbuffer")
    return tflite.Model.GetRootAsModel(buf, 0)


def tensors(model):
    g = model.Subgraphs(0)
    for i in range(g.TensorsLength()):
        t = g.Tensors(i)
        b = model.Buffers(t.Buffer())
        shape = [int(s) for s in t.ShapeAsNumpy()] if t.ShapeLength() else []
        yield i, t, shape, (b.DataAsNumpy() if b is not None and b.DataLength() else None)


def op_names(model) -> list:
    names = set()
    for i in range(model.OperatorCodesLength()):
        c = model.OperatorCodes(i)
        code = max(c.BuiltinCode(), c.DeprecatedBuiltinCode())
        names.add(OP_NAME.get(code, f"OP_{code}"))
    return sorted(names)


def camel(op: str) -> str:   # FULLY_CONNECTED -> FullyConnected (TFLM MicroMutableOpResolver::Add...)
    return "".join(p.title() for p in op.split("_"))


def info(path: Path) -> dict:
    model = load(path)
    g = model.Subgraphs(0)
    arena = 0
    for _, t, shape, data in tensors(model):
        if data is None:
            arena += int(np.prod(shape or [1])) * DTYPE_SIZE.get(t.Type(), 4)
    raw = path.read_bytes()
    io = lambda idx: DTYPE_NAME.get(g.Tensors(idx).Type(), "?").lower()
    return {
        "file": path.name, "size": len(raw), "gzip_size": len(gzip.compress(raw, 9)),
        "input": io(g.Inputs(0)), "output": io(g.Outputs(0)),
        "ops": op_names(model), "arena_upper_bound": arena,
    }


def weights(path: Path) -> list:
    model = load(path)
    rows = []
    for i, t, shape, data in tensors(model):
        if data is None or len(shape) < 2 or t.Type() not in DTYPE_NP:
            continue
        w = np.frombuffer(data.tobytes(), dtype=DTYPE_NP[t.Type()])
        rows.append({"tensor": t.Name().decode(), "shape": shape, "dtype": DTYPE_NAME[t.Type()].lower(),
                     "zero_fraction": round(float(np.mean(w == 0)), 4), "unique": int(len(np.unique(w)))})
    return rows


def carray(path: Path, name: str, outdir: Path) -> None:
    raw = path.read_bytes()
    ops = op_names(load(path))
    outdir.mkdir(parents=True, exist_ok=True)
    guard = name.upper()
    (outdir / f"{name}_model_data.h").write_text(
        f"/* {path.name} as a C array for TensorFlow Lite Micro (generated by tflite_info.py) */\n"
        f"#ifndef {guard}_MODEL_DATA_H\n#define {guard}_MODEL_DATA_H\n"
        f"extern const unsigned char {name}_model_data[];\nextern const unsigned int {name}_model_data_len;\n#endif\n")
    lines = ",\n".join("  " + ", ".join(f"0x{b:02x}" for b in raw[i:i + 12]) for i in range(0, len(raw), 12))
    (outdir / f"{name}_model_data.c").write_text(
        f'#include "{name}_model_data.h"\n'
        "/* 16-byte alignment: TFLM reads the flatbuffer in place from flash */\n"
        f"__attribute__((aligned(16))) const unsigned char {name}_model_data[] = {{\n{lines}\n}};\n"
        f"const unsigned int {name}_model_data_len = {len(raw)};\n")
    adds = "\n".join(f"  resolver.Add{camel(op)}();   /* {op} */" for op in ops)
    (outdir / f"{name}_op_resolver.h").write_text(
        f"/* Operators used by {path.name}: register exactly these with TFLM (C++). */\n"
        f"#ifndef {guard}_OP_RESOLVER_H\n#define {guard}_OP_RESOLVER_H\n"
        f"#define {guard}_OP_COUNT {len(ops)}\n"
        "#ifdef __cplusplus\n#include \"tensorflow/lite/micro/micro_mutable_op_resolver.h\"\n"
        f"static inline void {name}_register_ops(tflite::MicroMutableOpResolver<{guard}_OP_COUNT> &resolver) {{\n"
        f"{adds}\n}}\n#endif\n#endif\n")


def main() -> int:
    if len(sys.argv) < 3:
        print(__doc__); return 2
    cmd, files = sys.argv[1], [Path(f) for f in sys.argv[2:]]
    if cmd == "info":
        for f in files:
            d = info(f)
            print(f"{d['file']:32s} size={d['size']:6d} gzip={d['gzip_size']:6d} in={d['input']:7s} "
                  f"out={d['output']:7s} arena<={d['arena_upper_bound']:6d} ops={','.join(d['ops'])}")
    elif cmd == "json":
        print(json.dumps(info(files[0])))
    elif cmd == "weights":
        for r in weights(files[0]):
            print(f"{r['tensor'][:48]:48s} {str(r['shape']):18s} {r['dtype']:6s} zeros={r['zero_fraction']:.3f} "
                  f"unique={r['unique']}")
    elif cmd == "carray" and len(sys.argv) == 5:
        carray(Path(sys.argv[2]), sys.argv[3], Path(sys.argv[4]))
        print(f"wrote {sys.argv[4]}/{sys.argv[3]}_model_data.{{h,c}}, {sys.argv[3]}_op_resolver.h")
    else:
        print(__doc__); return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
